def write_topic(base_dir: Path, topic: Topic) -> None:
    day_dir = base_dir / topic.date
    day_dir.mkdir(parents=True, exist_ok=True)
    (day_dir / "1. 题目.md").write_text(build_prompt_md(topic), encoding="utf-8")
    (day_dir / "2. 写作要点.md").write_text(build_points_md(topic), encoding="utf-8")
    (day_dir / "3. 范文.md").write_text(build_essay_md(topic), encoding="utf-8")
    (day_dir / "更多写作思路.md").write_text(build_more_md(topic), encoding="utf-8")


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    base_dir = repo_root / "2027-每日作文"
    base_dir.mkdir(parents=True, exist_ok=True)

    total = len(TOPICS)
    for index, topic in enumerate(TOPICS, start=1):
        print(f"[task_boundary:start] {index}/{total} {topic.date}")
        write_topic(base_dir, topic)
        print(f"[task_boundary:end]   {index}/{total} {topic.date}")


if __name__ == "__main__":
    main()
