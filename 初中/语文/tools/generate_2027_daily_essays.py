def build_prompt_md(topic: Topic) -> str:
    return "\n".join(
        [
            "# 今日作文题目",
            "",
            "## 题目",
            "",
            topic.prompt,
            "",
            "请写一篇不少于 600 字的记叙文，可适当穿插抒情与议论。",
            "",
            "## 题目类型",
            "",
            topic.topic_type,
            "",
            "## 选题理由",
            "",
            topic.reason,
            "",
        ]
    )


